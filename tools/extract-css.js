// Extracts legacy CSS verbatim: src/styles/legacy.css (both <style> blocks) and src/styles/print.css (@media print blocks only).
const fs = require('fs');
const L = fs.readFileSync('legacy/app.html', 'utf8').split('\n');
const blk = (a, b) => L.slice(a - 1, b).join('\n'); // 1-based inclusive
const legacy = blk(9, 428) + '\n' + blk(431, 447) + '\n';
fs.mkdirSync('src/styles', { recursive: true });
fs.writeFileSync('src/styles/legacy.css', '/* VERBATIM from legacy/app.html lines 9-428 and 431-447. Generated by tools/extract-css.js — do not edit. */\n' + legacy);
// print blocks: find "@media print{" starting at col 0 / line start and balance braces
const css = legacy; const out = []; let i = 0;
while ((i = css.indexOf('@media print', i)) !== -1) {
  let d = 0, j = css.indexOf('{', i);
  for (let k = j; k < css.length; k++) { if (css[k] === '{') d++; else if (css[k] === '}') { d--; if (d === 0) { out.push(css.slice(i, k + 1)); i = k + 1; break; } } }
}
fs.writeFileSync('src/styles/print.css', '/* @media print blocks of legacy.css, used as a raw string by Blob print documents. Generated by tools/extract-css.js. */\n' + out.join('\n\n') + '\n');
console.log('legacy', legacy.length, 'print blocks', out.length);
